def snap(rgb):
    d=((rgb.astype(float)[...,None,:]-PAL.astype(float))**2).sum(-1)
    return d.argmin(-1).astype(np.uint8)

def prepare():
    (P/'frames').mkdir(exist_ok=True)
    shutil.copyfile(P/'refs/still_s.png',P/'frames/front_f0.png')
    # Sheet segmentation follows the six disconnected drawings on magenta.
    fg=(raw[:,:,1]>60)|(raw[:,:,0]<180)|(raw[:,:,2]<140)
    lab,n=nd.label(fg,np.ones((3,3)))
    objects=[]
    for i,s in enumerate(nd.find_objects(lab),1):
        if s and (lab[s]==i).sum()>1000:objects.append(s)
    objects.sort(key=lambda s:s[1].start)
    assert len(objects)==6,len(objects)
    ims=[]
    for f,s in enumerate(objects):
        old=np.array(Image.open(P/f'refs/pose_f{f}.png').convert('RGBA'))
        mask=old[:,:,3]>0;y,x=np.where(mask);box=(x.min(),y.min(),x.max()+1,y.max()+1)
        cell=Image.fromarray(raw[s]).resize((box[2]-box[0],box[3]-box[1]),Image.Resampling.NEAREST)
        idx=snap(np.array(cell));srcfg=nd.binary_fill_holes(np.array(Image.fromarray((fg[s]*255).astype('uint8')).resize(cell.size,Image.Resampling.NEAREST))>0)
        # Whole generated drawing first, then redraw boundary pixels to target alpha.
        nearest=nd.distance_transform_edt(~srcfg,return_distances=False,return_indices=True)
        idx[~srcfg]=idx[tuple(nearest[:,~srcfg])]
        a=np.zeros((160,160,4),dtype=np.uint8)
        a[box[1]:box[3],box[0]:box[2],:3]=PAL[idx]
        a[:,:,3]=mask*255
        a[~mask]=0
        if f:Image.fromarray(a).save(P/f'frames/front_f{f}.png')
        ims.append(a)
    board=Image.new('RGB',(6*95*6,90*6),'#5a6058')
    for f,a in enumerate(ims):
        im=Image.fromarray(a).crop((25,65,120,155)).resize((570,540),Image.Resampling.NEAREST)
        board.paste(im,(f*570,0),im)
    board.save(P/'work_extracted.png')

