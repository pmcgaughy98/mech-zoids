def length(p):return round(1+sum(hypot(b[0]-a[0],b[1]-a[1]) for a,b in zip(p,p[1:])),2) if p else None
def cross(a,root,tip,t=.6):
 root=np.array(root,float);tip=np.array(tip,float);axis=tip-root;n=np.array([-axis[1],axis[0]])/np.linalg.norm(axis);p=root+axis*t
 def hit(z):
  x,y=np.rint(p+n*z).astype(int)
  return bool(0<=x<192 and 0<=y<192 and a[y,x,3]>0)
 if not hit(0):return None
 lo=hi=0.
 while lo>-15 and hit(lo-.25):lo-=.25
 while hi<15 and hit(hi+.25):hi+=.25
 return round(hi-lo+1,2)

